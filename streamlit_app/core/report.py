"""One-page, self-contained HTML run report (print to PDF from the browser)."""
from __future__ import annotations

import base64
import html
import json
from pathlib import Path
from typing import Any

from core.settings import redact
from core.storage import RunRecord, is_licensed


def _img(p: Path, max_bytes: int = 4_000_000) -> str:
    if p.stat().st_size > max_bytes:
        return ""
    b64 = base64.b64encode(p.read_bytes()).decode()
    return f'<figure><img alt="{html.escape(p.name)}" src="data:image/png;base64,{b64}"><figcaption>{html.escape(p.name)}</figcaption></figure>'


def _table(d: dict[str, Any]) -> str:
    rows = "".join(f"<tr><th>{html.escape(str(k))}</th><td>{html.escape(json.dumps(v, default=str) if isinstance(v, (dict, list)) else str(v))}</td></tr>"
                   for k, v in d.items())
    return f"<table>{rows}</table>"


def build_report(rec: RunRecord, extra_sections: dict[str, str] | None = None) -> str:
    meta, inputs, result, env = rec.meta, rec.inputs(), rec.result() or {}, rec.env()
    title = meta.get("label") or f"{meta.get('tool_title', meta.get('tool'))}"
    res_public = {k: v for k, v in result.items() if k not in ("traceback",)}
    pngs = [p for p in rec.output_files() if p.suffix.lower() == ".png" and not is_licensed(p)][:12]
    files = [p.relative_to(rec.files_dir).as_posix() for p in rec.output_files() if not is_licensed(p)]
    log_tail = html.escape(redact("\n".join(rec.log_text(20_000).splitlines()[-40:])))
    status_colour = {"succeeded": "#1a7f37", "failed": "#cf222e", "cancelled": "#9a6700"}.get(meta.get("status"), "#57606a")
    extra = "".join(f"<h2>{html.escape(k)}</h2>{v}" for k, v in (extra_sections or {}).items())
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>{html.escape(title)}</title>
<style>
:root{{--fg:#1f2328;--muted:#57606a;--line:#d0d7de;--bg:#fff}}
@media (prefers-color-scheme:dark){{:root{{--fg:#e6edf3;--muted:#8d96a0;--line:#30363d;--bg:#0d1117}}}}
body{{font-family:system-ui,-apple-system,Segoe UI,sans-serif;color:var(--fg);background:var(--bg);max-width:960px;margin:24px auto;padding:0 16px;line-height:1.45}}
h1{{margin:0 0 4px}} h2{{border-bottom:1px solid var(--line);padding-bottom:4px;margin-top:28px;font-size:1.15rem}}
.badge{{display:inline-block;padding:2px 10px;border-radius:12px;color:#fff;background:{status_colour};font-size:.85rem}}
.muted{{color:var(--muted)}} table{{border-collapse:collapse;width:100%;font-size:.9rem}}
th,td{{border:1px solid var(--line);padding:4px 8px;text-align:left;vertical-align:top}} th{{width:32%;font-weight:600}}
pre{{background:#8881;padding:8px;border-radius:6px;overflow:auto;font-size:.8rem;max-height:420px}}
figure{{margin:8px 0;display:inline-block;width:48%;vertical-align:top}} img{{max-width:100%;border:1px solid var(--line);border-radius:6px}}
figcaption{{font-size:.8rem;color:var(--muted)}} @media print{{figure{{width:48%}} pre{{max-height:none}}}}
</style></head><body>
<h1>{html.escape(title)}</h1>
<p class="muted">Masgent run report · <span class="badge">{html.escape(str(meta.get('status')))}</span> · run <code>{html.escape(rec.run_id)}</code></p>
<h2>Summary</h2>{_table({"Tool": meta.get("tool_title"), "Masgent function": meta.get("func"), "Project": meta.get("project"),
 "Created": meta.get("created"), "Duration (s)": meta.get("duration_s"), "Device": meta.get("device"), "Seed": meta.get("seed"),
 "Tags": ", ".join(meta.get("tags") or []), "Notes": meta.get("notes") or "", **(meta.get("summary") or {})})}
{f'<p><b>Error:</b> {html.escape(str(meta.get("error")))}</p>' if meta.get("error") else ''}
<h2>Parameters</h2>{_table(inputs.get("params", {}))}
<h2>Result</h2>{_table(res_public)}
{extra}
<h2>Figures</h2>{''.join(_img(p) for p in pngs) or '<p class="muted">No figures produced.</p>'}
<h2>Output files</h2><pre>{html.escape(chr(10).join(files)) or 'none'}</pre>
<h2>Provenance</h2>{_table({"Python": env.get("python"), "Platform": env.get("platform"), **(env.get("packages") or {})})}
<h2>Log (last 40 lines)</h2><pre>{log_tail}</pre>
<p class="muted">Generated by the Masgent Streamlit app. POTCAR files are never included.</p>
</body></html>"""
